export type TranslationKey = keyof typeof TRANSLATIONS.de;

export function getLanguage(): Language {
  return currentLang;
}

export function setLanguage(lang: Language): void {
  if (currentLang === lang) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  for (const fn of listeners) fn(lang);
}

export function t(key: string, ...args: Array<string | number>): string {
  const dict = TRANSLATIONS[currentLang] as Record<string, string>;
  const fallbackDict = TRANSLATIONS.de as Record<string, string>;
  let text = dict[key] ?? fallbackDict[key] ?? key;

  if (args.length > 0) {
    for (let i = 0; i < args.length; i++) {
      text = text.replace(new RegExp(`\\{${i}\\}`, 'g'), `${args[i]}`);
    }
  }
  return text;
}

export function onLanguageChange(fn: (lang: Language) => void): () => void {
  listeners.push(fn);
  return () => {
    const idx = listeners.indexOf(fn);
    if (idx >= 0) listeners.splice(idx, 1);
  };
}

